//! The HTML parser's SVG rules: which parsed elements are in the SVG namespace
//! and the case their names take there (HTML §13.2.6.5). The tokenizer
//! lowercases every name, so the tree builder's open-element stack stays
//! lowercase; only the node the sink makes carries the adjusted name.

pub(crate) const SVG_NAMESPACE: &str = "http://www.w3.org/2000/svg";

/// HTML integration points in SVG, by their adjusted names: their children
/// are HTML.
pub(crate) fn is_html_integration_point(tag_name: &str) -> bool {
    matches!(tag_name, "foreignObject" | "desc" | "title")
}

/// A start tag that leaves foreign content. `font` does so only with `color`,
/// `face` or `size`.
pub(crate) fn breaks_out_of_svg(name: &str, attrs: &[(String, String)]) -> bool {
    match name {
        "b" | "big" | "blockquote" | "body" | "br" | "center" | "code" | "dd" | "div" | "dl"
        | "dt" | "em" | "embed" | "h1" | "h2" | "h3" | "h4" | "h5" | "h6" | "head" | "hr" | "i"
        | "img" | "li" | "listing" | "menu" | "meta" | "nobr" | "ol" | "p" | "pre" | "ruby"
        | "s" | "small" | "span" | "strong" | "strike" | "sub" | "sup" | "table" | "tt" | "u"
        | "ul" | "var" => true,
        "font" => attrs.iter().any(|(k, _)| matches!(k.as_str(), "color" | "face" | "size")),
        _ => false,
    }
}

